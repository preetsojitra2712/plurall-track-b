#!/usr/bin/env python3
"""Aggregate tonight's result files into data/results_summary.md.

Data aggregation only: every number is read from the artifact files on disk,
never retyped. No interpretation is added -- tables and their provenance only.
"""
import json
import os
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from pk import metrics as M  # noqa: E402

OUT = Path("data/results_summary.md")
parts: list[str] = ["# Results summary (aggregated from artifacts, 2026-08-14)",
                    "", "Generated by `scripts/build_results_summary.py`. "
                    "Numbers are read from the listed artifact files; nothing is retyped.", ""]


def md_table(df: pd.DataFrame, floatfmt: str = "{:.3f}") -> str:
    d = df.copy()
    for c in d.columns:
        if d[c].dtype.kind == "f":
            d[c] = d[c].map(lambda v: "" if pd.isna(v) else floatfmt.format(v))
    header = "| " + " | ".join(map(str, d.columns)) + " |"
    sep = "|" + "|".join("---" for _ in d.columns) + "|"
    rows = ["| " + " | ".join(map(str, r)) + " |" for r in d.itertuples(index=False)]
    return "\n".join([header, sep] + rows)


# ---- 1/2. layer probe curves, pre- and post-channel-equalisation ----------
for path, tag in [("data/layer_probe_results_before_eq.csv",
                   "before channel equalisation (archived)"),
                  ("data/layer_probe_results.csv",
                   "after channel equalisation (current)")]:
    p = Path(path)
    if not p.exists():
        continue
    df = pd.read_csv(p)
    parts += [f"## Layer-wise frozen linear probe — {tag}",
              f"Produced by `scripts/probe_layers.py` → `{path}`", "",
              md_table(df), ""]

# ---- 3. GPU run metrics ---------------------------------------------------
gj = Path("data/gpu_run_metrics.json")
if gj.exists():
    m = json.loads(gj.read_text())
    rows = [dict(run=k, **v) for k, v in m.items()]
    df = pd.DataFrame(rows)
    parts += ["## GPU run (H100) — corrected LoRA experiment",
              "Produced by `scripts/control_head_only.py`, "
              "`scripts/train_lora_probe_v2.py`, `scripts/probe_adapted_features.py` "
              "→ `data/gpu_run_metrics.json`", "",
              md_table(df), ""]

# ---- 4. clean vs telephone-degraded ---------------------------------------
ds = Path("data/degraded_scores.csv")
if ds.exists():
    df = pd.read_csv(ds)
    rows = []
    for deg in ("none", "telephone"):
        sub = df[df.degradation == deg]
        y = sub["label"].to_numpy()
        for col, model in [("score_frozen", "frozen sklearn probe"),
                           ("score_lora", "LoRA-adapted (v2)")]:
            s = sub[col].to_numpy()
            rows.append(dict(model=model, degradation=deg, n=len(sub),
                             auc=M.roc_auc(y, s), eer=M.eer(y, s)[0]))
    parts += ["## Clean vs telephone-degraded — test split (authentic + piper)",
              "Produced by `scripts/eval_degraded.py` → `data/degraded_scores.csv` "
              "(aggregated with `pk.metrics`)", "",
              md_table(pd.DataFrame(rows)), ""]

# ---- 5. Gaussian confidence -----------------------------------------------
gc = Path("data/gaussian_confidence_test.csv")
if gc.exists():
    df = pd.read_csv(gc)
    rows = []
    for (scen, gen), g in df.groupby(["scenario", "generator"]):
        bands = g["band"].value_counts().to_dict()
        rows.append(dict(
            scenario=scen, generator=gen, n=len(g),
            sig_auth_med=g["sigmas_from_authentic"].median(),
            sig_auth_min=g["sigmas_from_authentic"].min(),
            sig_auth_max=g["sigmas_from_authentic"].max(),
            sig_spoof_med=g["sigmas_from_spoof"].median(),
            sig_spoof_min=g["sigmas_from_spoof"].min(),
            sig_spoof_max=g["sigmas_from_spoof"].max(),
            posterior_med=g["posterior"].median(),
            bands=" ".join(f"{k}:{v}" for k, v in sorted(bands.items()))))
    parts += ["## Gaussian confidence — per-generator summary",
              "Produced by `scripts/gaussian_confidence_report.py` "
              "→ `data/gaussian_confidence_test.csv`", "",
              md_table(pd.DataFrame(rows)), ""]

OUT.write_text("\n".join(parts), encoding="utf-8")
print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
print("sections:", sum(1 for p in parts if p.startswith("## ")))
